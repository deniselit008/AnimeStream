export function resolveAnimeCover(item) {
  if (!item) return getDefaultPoster();
  const img = item.image;
  if (img && !img.includes('placeholder.com') && !img.includes('undefined') && !img.includes('null') && img.startsWith('http')) {
    return img;
  }
  
  // Try extracting slug from url or animeUrl if JKAnime
  const url = item.animeUrl || item.url || '';
  const src = (item.source || '').toLowerCase();
  if (src.includes('jk') || url.includes('jkanime.net')) {
    const m = url.match(/jkanime\.net\/([^\/]+)/);
    if (m && m[1] && m[1] !== 'directorio' && m[1] !== 'buscar') {
      return `https://cdn.jkdesa.com/assets/images/animes/image/${m[1]}.jpg`;
    }
  }

  return getDefaultPoster(item.animeTitle || item.title || 'Anime', item.source || '');
}

export function getSourceBadgeClass(source) {
  const s = (source || '').toLowerCase();
  if (s.includes('av1') || s.includes('animeav1')) return 'badge-av1';
  if (s.includes('jk') || s.includes('jkanime')) return 'badge-jk';
  if (s.includes('tio') || s.includes('tioanime')) return 'badge-tio';
  return 'badge-av1';
}

export function debounce(fn, delay = 300) {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), delay);
  };
}

export function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

export function timeAgo(timestamp) {
  if (!timestamp) return '';
  const now = Date.now();
  const diffSec = Math.floor((now - timestamp) / 1000);

  if (diffSec < 60) return 'Hace un momento';
  const diffMin = Math.floor(diffSec / 60);
  if (diffMin < 60) return `Hace ${diffMin} min`;
  const diffHour = Math.floor(diffMin / 60);
  if (diffHour < 24) return `Hace ${diffHour} h`;
  const diffDays = Math.floor(diffHour / 24);
  if (diffDays === 1) return 'Ayer';
  return `Hace ${diffDays} días`;
}

export function showToast(message, type = 'info', duration = 3000) {
  let container = document.querySelector('.toast-container');
  if (!container) {
    container = document.createElement('div');
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.innerHTML = `<span>${escapeHtml(message)}</span>`;

  container.appendChild(toast);
  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(10px)';
    toast.style.transition = 'all 0.3s ease';
    setTimeout(() => toast.remove(), 300);
  }, duration);
}

export function fixEncoding(str) {
  if (!str || typeof str !== 'string') return str;
  if (/Ã|Â|â|ð|ï¿½/.test(str)) {
    try {
      return decodeURIComponent(escape(str));
    } catch (e) {
      return str;
    }
  }
  return str;
}

export function slugifyGenre(genre) {
  if (!genre) return 'all';
  const clean = fixEncoding(String(genre).trim().toLowerCase());
  return clean
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '');
}

export function getRelationBadgeClass(rel) {
  const r = (rel || '').toLowerCase();
  if (r.includes('secuela') || r.includes('sequel')) return 'badge-relation-sequel';
  if (r.includes('precuela') || r.includes('prequel')) return 'badge-relation-prequel';
  if (r.includes('película') || r.includes('resumen') || r.includes('movie') || r.includes('summary')) return 'badge-relation-movie';
  if (r.includes('paralela') || r.includes('side') || r.includes('ova')) return 'badge-relation-side';
  if (r.includes('spin')) return 'badge-relation-spinoff';
  if (r.includes('adaptación') || r.includes('manga') || r.includes('novela')) return 'badge-relation-manga';
  return 'badge-relation-other';
}


